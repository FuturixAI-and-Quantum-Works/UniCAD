"""Derive per-character advance widths from a LibreCAD .lff font.

Usage: python tools/gen_text_metrics.py /path/to/standard.lff > src/unicad/drafting/sheets/textmetrics.py
"""

import re
import sys
from pathlib import Path

CAP_HEIGHT = 9.0


def parse(path: Path) -> tuple[dict[int, float], float, float]:
    letter_spacing = word_spacing = 0.0
    glyphs: dict[int, list[str]] = {}
    current: list[str] | None = None
    for raw in path.read_text(encoding="utf-8").splitlines():
        if raw.startswith("#"):
            m = re.match(r"#\s*(LetterSpacing|WordSpacing):\s*([\d.]+)", raw)
            if m:
                if m.group(1) == "LetterSpacing":
                    letter_spacing = float(m.group(2))
                else:
                    word_spacing = float(m.group(2))
            continue
        m = re.match(r"\[([0-9a-fA-F]+)\]", raw)
        if m:
            current = glyphs.setdefault(int(m.group(1), 16), [])
        elif current is not None and raw.strip():
            current.append(raw.strip())

    def extent(code: int, seen: frozenset[int] = frozenset()) -> float:
        xs = [0.0]
        for line in glyphs.get(code, []):
            if line.startswith("C") and code not in seen:
                xs.append(extent(int(line[1:], 16), seen | {code}))
                continue
            for point in line.split(";"):
                head = point.split(",")[0]
                try:
                    xs.append(float(head))
                except ValueError:
                    pass
        return max(xs)

    widths = {c: extent(c) + letter_spacing for c in glyphs if 0x21 <= c <= 0x7E}
    return widths, word_spacing, letter_spacing


def main() -> None:
    widths, word_spacing, _ = parse(Path(sys.argv[1]))
    print('"""Advance widths of LibreCAD\'s `standard` font, in text heights.')
    print()
    print("Generated by tools/gen_text_metrics.py. Do not edit.")
    print('"""')
    print()
    print("ADVANCE: dict[str, float] = {")
    print(f'    " ": {word_spacing / CAP_HEIGHT:.4f},')
    for code in sorted(widths):
        ch = chr(code)
        key = ch.replace("\\", "\\\\").replace('"', '\\"')
        print(f'    "{key}": {widths[code] / CAP_HEIGHT:.4f},')
    print("}")


if __name__ == "__main__":
    main()

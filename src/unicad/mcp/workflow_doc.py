def abbreviate(value: Any) -> Any:
    if isinstance(value, dict):
        return {k: abbreviate(v) for k, v in value.items()}
    if isinstance(value, list):
        out = [abbreviate(v) for v in value[:LIST_LIMIT]]
        return out + [f"... {len(value) - LIST_LIMIT} more"] if len(value) > LIST_LIMIT else out
    if isinstance(value, str) and len(value) > TEXT_LIMIT:
        return value[: TEXT_LIMIT - 3].rstrip() + "..."
    return value


def _dump(value: Any, indent: int = 0) -> str:
    """JSON with objects and lists that fit on one line kept on one line."""
    flat = json.dumps(value, ensure_ascii=False)
    if not isinstance(value, dict | list) or len(flat) + indent <= INLINE_WIDTH or not value:
        return flat
    pad = " " * (indent + 2)
    if isinstance(value, list):
        return "[\n" + ",\n".join(pad + _dump(v, indent + 2) for v in value) + "\n" + " " * indent + "]"
    return "{\n" + ",\n".join(f"{pad}{json.dumps(k)}: {_dump(v, indent + 2)}" for k, v in value.items()) + "\n" + " " * indent + "}"


def _py(value: Any) -> str:
    if isinstance(value, bool | None):
        return str(value)
    if isinstance(value, dict):
        return "{" + ", ".join(f"{json.dumps(k)}: {_py(v)}" for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "[" + ", ".join(_py(v) for v in value) + "]"
    return json.dumps(value, ensure_ascii=False)


def _call_text(tool: str, args: dict[str, Any]) -> str:
    pairs = [f"{k}={_py(v)}" for k, v in args.items()]
    if len(", ".join(pairs)) <= CALL_WIDTH:
        return f"{tool}({', '.join(pairs)})"
    return "\n".join([f"{tool}(", *[f"    {pair}," for pair in pairs], ")"])


def _normalise(text: str, workspace: Path) -> str:
    return text.replace(str(workspace), "<workspace>").replace(str(REPO) + "/", "")


async def _transcript(workspace: Path) -> list[str]:
    server = build_server(Config(workspace=workspace))
    out: list[str] = []
    async with Client(server) as client:
        for n, step in enumerate(steps(), 1):
            args = {k: (str(REPO / v) if k in PATH_ARGS else v) for k, v in step.args.items()}
            result = await client.call_tool(step.tool, args)
            if result.is_error:
                raise RuntimeError(f"workflow step {n} ({step.tool}) failed: {result.content[0].text}")
            data = result.structured_content or {}
            if step.keep is not None:
                data = {k: data[k] for k in step.keep if k in data}
            if step.edit is not None:
                data = step.edit(data)
            data = json.loads(_normalise(json.dumps(data), workspace))
            shown = _dump(abbreviate(data))
            out += [
                f"### {n}. `{step.tool}`",
                "",
                step.note,
                "",
                "```python",
                _normalise(_call_text(step.tool, args), workspace),
                "```",
                "",
                "```json",
                shown,
                "```",
                "",
            ]
    return out


def _prompt_section(title: str, text: str) -> list[str]:
    return [f"### `{title}`", "", "```text", text, "```", ""]


async def render_workflow_markdown() -> str:
    with tempfile.TemporaryDirectory(prefix="unicad-workflow-") as tmp:
        transcript = await _transcript(Path(tmp).resolve() / "workspace")
    lines = [HEADER, "## Server instructions", "", "```text", INSTRUCTIONS, "```", "", "## Prompts", ""]
    lines += _prompt_section("new_rooftop_project(name)", ROOFTOP.format(name="<name>"))
    lines += _prompt_section("new_utility_project(name)", UTILITY.format(name="<name>"))
    lines += _prompt_section("new_bess_project(name)", BESS.format(name="<name>"))
    lines += _prompt_section("revise_after_comments(project_id, comments)", REVISE.format(project_id="<project_id>", comments="<comments>"))
    lines += [
        "## Worked example",
        "",
        "A rooftop plant on the survey `fixtures/sites/rooftop_midc_pune.kml`, from an empty workspace to a diffed revision. Results are abbreviated: lists keep their first four items, long text is cut and keys that do not matter to the step are left out. Equipment ids come from the catalog; values the example's user supplies are named as such.",
        "",
    ]
    lines += transcript
    return "\n".join(lines).rstrip() + "\n"
